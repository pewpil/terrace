// Regenerates terrace's english vocabulary table from an open frequency
// corpus. Node-side script (no-console exemption applies to scripts/*.mjs).
//
// Source: hermitdave/FrequencyWords "OpenSubtitles 2018" english frequency
// list, en_full.txt (rank-ordered word + occurrence count, ~600k lines).
// This is open, neutral corpus data - not another typing app's asset.
// terrace owns the filtering and the difficulty banding; see
// app/utils/word-list.ts.
//
// Filter rules:
// - keep /^[a-z]{2,}$/ tokens, plus the single-letter words "a" and "i"
//   (fragments like clitic "s"/"t", hyphenated compounds and abbreviations
//   with apostrophes are dropped; rank order is preserved)
//
// Usage: node scripts/build-vocab.mjs   (fetches, then overwrites the table)

import { mkdir, writeFile } from 'node:fs/promises'
import { dirname } from 'node:path'

const SOURCE_URL =
  'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_full.txt'

const OUT_PATH = 'app/utils/vocab/en-ranked.ts'

const res = await fetch(SOURCE_URL)
if (!res.ok) {
  console.error(`fetch failed: ${res.status} ${res.statusText}`)
  process.exit(1)
}
const text = await res.text()

const lines = text.split('\n')
const keep = []
const keptCounts = []
const VOCAB_SIZE = 50_000
for (const line of lines) {
  if (keep.length >= VOCAB_SIZE) break
  const cut = line.indexOf(' ')
  if (cut < 0) continue
  const word = line.slice(0, cut)
  const count = Number(line.slice(cut + 1))
  if (!Number.isFinite(count) || count <= 0) continue
  if (!/^[a-z]+$/.test(word)) continue
  if (word.length < 2 && word !== 'a' && word !== 'i') continue
  keep.push(word)
  keptCounts.push(count)
}

if (keep.length !== VOCAB_SIZE) {
  console.error(
    `unexpected filtered vocabulary size: ${keep.length} (want ${VOCAB_SIZE}) ` +
      '- the tier bands in app/utils/word-list.ts would need re-cutting',
  )
  process.exit(1)
}

const body = keep.map((w, i) => `${w} ${keptCounts[i]}`).join('\n')

const header = `/**
 * generated by scripts/build-vocab.mjs - do not edit by hand.
 *
 * english vocabulary, rank-ordered: 50k lines of "word occurrenceCount",
 * descending by subtitle-driven frequency (terrace bands it into
 * difficulties in app/utils/word-list.ts).
 *
 * source: hermitdave/FrequencyWords (OpenSubtitles 2018 en_50k.txt), open
 * data; filtered to /^[a-z]{2,}$/ plus the single-letter words "a" and "i".
 */

export const ENGLISH_RANKED_RAW = \`
${body}
\`
`

await mkdir(dirname(OUT_PATH), { recursive: true })
await writeFile(OUT_PATH, `${header}\n`)

const band = (from, to) => {
  const first = keep[from - 1]
  const last = keep[to - 1]
  return `${first} -> ${last}`
}
console.log(`wrote ${OUT_PATH} with ${keep.length} words`)
console.log('band edges (1-based rank, inclusive):')
console.log(`  beginner      1-1000    ${band(1, 1000)}`)
console.log(`  elementary    1001-3000 ${band(1001, 3000)}`)
console.log(`  intermediate  3001-6000 ${band(3001, 6000)}`)
console.log(`  advanced      6001-12000 ${band(6001, 12000)}`)
console.log(`  expert        12001-25000 ${band(12001, 25000)}`)
console.log(`  master        25001-50000 ${band(25001, 50000)}`)
